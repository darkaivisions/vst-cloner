import type { CaptureRender, Parameter } from "@vst-cloner/profile";
import { cppNumber, cppString, parameterLines } from "../eq/codegen.ts";
import type { CloneParam } from "../eq/params.ts";
import { dynamicsCloneParameters } from "../dynamics/params.ts";

/** Network trained by dsp/neural/train.py (model.json). Matrices as written there: rows × columns. */
export interface NeuralModel {
  sampleRate: number;
  /** indices of the original's parameters the network is conditioned on, in input order */
  parameters: number[];
  names: string[];
  hidden: number;
  inputs: number;
  outputs: number;
  /** W: inputs × 4·hidden, U: hidden × 4·hidden, b: 4·hidden; gate order i, f, g, o */
  lstm: { W: number[][]; U: number[][]; b: number[] };
  /** W: outputs × hidden */
  dense: { W: number[][]; b: number[] };
  /** W1: filmHidden × max(1, conditions), W2: (2·hidden + outputs [+ 1 level row]) × filmHidden */
  film: { W1: number[][]; b1: number[]; W2: number[][]; b2: number[] };
  /** per conditioning input: positions of a control that moves in steps (the network saw their middles), or null */
  positions?: ({ values: number[]; bounds: [number, number][] } | null)[];
}

/** C++ function that maps a conditioning input to the middle of its position, as train.py's snap() does. */
function snapLines(model: NeuralModel): string[] {
  const cases = (model.positions ?? []).flatMap((pos, c) => {
    if (!pos || pos.values.length === 0) return [];
    const list = (values: number[]) => values.map((v) => cppNumber(Math.fround(v)) + "f").join(", ");
    return [
      `        case ${c}:`,
      "        {",
      `            static constexpr float lo[] = { ${list(pos.bounds.map((b) => b[0]))} };`,
      `            static constexpr float hi[] = { ${list(pos.bounds.map((b) => b[1]))} };`,
      `            static constexpr float mid[] = { ${list(pos.values)} };`,
      `            return snapPosition (lo, hi, mid, ${pos.values.length}, value);`,
      "        }",
    ];
  });
  return [
    "// middle of the position a value falls into: the one whose range contains it, else the nearest",
    "inline float snapPosition (const float* lo, const float* hi, const float* mid, int n, float value)",
    "{",
    "    int best = 0;",
    "    float distance = 1.0e9f;",
    "    for (int i = 0; i < n; ++i)",
    "    {",
    "        const float d = value < lo[i] ? lo[i] - value : value > hi[i] ? value - hi[i] : 0.0f;",
    "        if (d < distance) { best = i; distance = d; }",
    "    }",
    "    return mid[best];",
    "}",
    "// controls that move in steps: the network was trained on the middle of each position",
    "inline float snapCondition (int condition, float value)",
    "{",
    ...(cases.length ? ["    switch (condition)", "    {", ...cases, "        default: break;", "    }"] : ["    (void) condition;"]),
    "    return value;",
    "}",
  ];
}

const floats = (values: number[]) => values.map((v) => cppNumber(Math.fround(v))).join(", ");

/**
 * Generates CloneModel.h for plugin-template/neural: the clone's parameters (same names and ranges as the
 * original) and the network's weights in the layout NeuralEngine.h reads – U as one row of 4·hidden gate weights per
 * hidden component, so the per-sample loop runs over contiguous memory and vectorises.
 */
export function generateNeuralHeader(model: NeuralModel, parameters: Parameter[], pluginName: string, renders: CaptureRender[] = []): { header: string; params: CloneParam[] } {
  const params = dynamicsCloneParameters({ tables: model.parameters.map((index) => ({ index })) }, parameters, renders);
  const cloneIndex = new Map(params.map((p, i) => [p.original, i]));
  const H = model.hidden;
  const C = model.parameters.length;
  const gates = 4 * H;
  const W = model.lstm.W;
  if (W.length !== 1 + C || W[0]!.length !== gates) throw new Error(`model.json: LSTM input weights are ${W.length}×${W[0]?.length}, expected ${1 + C}×${gates}`);
  // U is hidden × 4·hidden (h_k → gate j): kept like that, the engine adds one such row per h component
  const uRows = model.lstm.U.flat();
  // knob weights: Wc[c][j]
  const wc = W.slice(1).flat();
  const filmHidden = model.film.W1.length;
  // models since the level row: gamma, beta, dry and a gain on a logarithmic scale
  const filmRows = model.film.W2.length;
  if (filmRows !== 2 * H + model.outputs && filmRows !== 2 * H + model.outputs + 1) throw new Error(`model.json: FiLM output has ${filmRows} rows, expected ${2 * H + model.outputs} or ${2 * H + model.outputs + 1}`);
  const filmLevel = filmRows === 2 * H + model.outputs + 1;

  const lines = [
    "// Generated by vst-cloner – do not edit.",
    "#pragma once",
    "",
    "namespace clonemodel",
    "{",
    `inline constexpr const char* pluginName = ${cppString(pluginName)};`,
    "",
    ...parameterLines(params),
    `inline constexpr int hidden = ${H};`,
    `inline constexpr int numConditions = ${C};`,
    `inline constexpr int filmHidden = ${filmHidden};`,
    `inline constexpr bool filmLevel = ${filmLevel};`,
    `inline constexpr double trainedSampleRate = ${cppNumber(model.sampleRate)};`,
    `// clone parameter of each network input: ${model.names.join(", ").replace(/[\r\n]/g, " ")}`,
    `inline constexpr int conditionParams[${Math.max(1, C)}] = { ${C ? model.parameters.map((i) => cloneIndex.get(i) ?? 0).join(", ") : "0"} };`,
    `inline const float lstmWx[${gates}] = { ${floats(W[0]!)} };`,
    `inline const float lstmWc[${Math.max(1, C * gates)}] = { ${C ? floats(wc) : "0.0f"} };`,
    `inline const float lstmB[${gates}] = { ${floats(model.lstm.b)} };`,
    `inline const float lstmU[${gates * H}] = { ${floats(uRows)} };`,
    `inline const float denseW[${H}] = { ${floats(model.dense.W[0]!)} };`,
    `inline constexpr float denseB = ${cppNumber(Math.fround(model.dense.b[0]!))};`,
    `inline const float filmW1[${model.film.W1.flat().length}] = { ${floats(model.film.W1.flat())} };`,
    `inline const float filmB1[${filmHidden}] = { ${floats(model.film.b1)} };`,
    `inline const float filmW2[${model.film.W2.flat().length}] = { ${floats(model.film.W2.flat())} };`,
    `inline const float filmB2[${model.film.b2.length}] = { ${floats(model.film.b2)} };`,
    ...snapLines(model),
    "} // namespace clonemodel",
    "",
  ];
  return { header: lines.join("\n"), params };
}
