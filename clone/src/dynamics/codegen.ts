import type { CaptureRender, Parameter } from "@vst-cloner/profile";
import { cppNumber, cppString, parameterLines } from "../eq/codegen.ts";
import type { CloneParam } from "../eq/params.ts";
import { latentPoint, NO_INTERACTION, pack, toLatent, type DynamicsModel, type DynamicsTables } from "./fit.ts";
import { dynamicsCloneParameters } from "./params.ts";

/** Generates CloneModel.h for plugin-template/dynamics. */
export function generateDynamicsHeader(
  model: DynamicsModel,
  parameters: Parameter[],
  pluginName: string,
  renders: CaptureRender[] = [],
): { header: string; params: CloneParam[] } {
  const params = dynamicsCloneParameters(model, parameters, renders);
  const cloneIndex = new Map(params.map((p, i) => [p.original, i]));
  const list = (values: number[]) => values.map(cppNumber).join(", ");

  const lines = [
    "// Generated by vst-cloner – do not edit.",
    "#pragma once",
    '#include "DynamicsEngine.h"',
    "",
    "namespace clonemodel",
    "{",
    `inline constexpr const char* pluginName = ${cppString(pluginName)};`,
    "",
    ...parameterLines(params),
  ];

  // model 0 is the main one; the others apply while their switch is in their position
  const models: { tables: DynamicsTables; condition: string; comment: string }[] = [
    { tables: model, condition: "-1, 0.0, 0.0", comment: "main model" },
    ...(model.variants ?? []).map((v) => ({
      tables: v as DynamicsTables,
      condition: `${cloneIndex.get(v.index)}, ${cppNumber(v.range[0])}, ${cppNumber(v.range[1])}`,
      comment: v.name.replace(/[\r\n]/g, " "),
    })),
  ];
  models.forEach((m, k) => {
    const interaction = m.tables.interaction ?? NO_INTERACTION;
    const baseValue = new Map(m.tables.baseValues.map((v) => [v.index, v.value]));
    lines.push(`// model ${k}: ${m.comment}`, `inline constexpr double baseLatent${k}[vch::numLatent] = { ${list(toLatent(pack(m.tables.base), 0, interaction))} };`);
    m.tables.tables.forEach((t, i) => {
      lines.push(`inline const double tableValues${k}_${i}[] = { ${list(t.points.map((p) => p.value))} };`);
      lines.push(`inline const double tablePacked${k}_${i}[] = { ${list(t.points.flatMap((p) => latentPoint(p.packed)))} };`);
    });
    if (m.tables.tables.length === 0) lines.push(`inline const vch::ParamTable* const tables${k} = nullptr;`);
    else {
      lines.push(`inline const vch::ParamTable tables${k}[] =`, "{");
      m.tables.tables.forEach((t, i) => {
        lines.push(`    { ${cloneIndex.get(t.index)}, ${t.discrete}, ${t.points.length}, tableValues${k}_${i}, tablePacked${k}_${i}, ${cppNumber(baseValue.get(t.index) ?? 0)} }, // ${t.name.replace(/[\r\n]/g, " ")}`);
      });
      lines.push("};");
    }
    lines.push("");
  });
  lines.push("inline const vch::DynamicsModelData models[] =", "{");
  models.forEach((m, k) => {
    const s = m.tables.structure, interaction = m.tables.interaction ?? NO_INTERACTION;
    lines.push(
      `    { ${m.condition}, vch::Detector::${s.detector}, vch::Topology::${s.topology}, vch::Curve::${s.curve ?? "compressor"}, baseLatent${k}, tables${k}, ${m.tables.tables.length}, ` +
        `{ ${cppNumber(interaction.autoMakeup)}, ${cppNumber(interaction.referenceDb)} } }, // ${m.comment}`,
    );
  });
  lines.push("};", `inline constexpr int numModels = ${models.length};`, "} // namespace clonemodel", "");
  return { header: lines.join("\n"), params };
}
