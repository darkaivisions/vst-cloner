import type { CaptureRender, Parameter } from "@vst-cloner/profile";
import { cppNumber, cppString, parameterLines } from "../eq/codegen.ts";
import type { CloneParam } from "../eq/params.ts";
import { pack, type DynamicsModel } from "./fit.ts";
import { dynamicsCloneParameters } from "./params.ts";

/** Generates CloneModel.h for plugin-template/dynamics. */
export function generateDynamicsHeader(
  model: DynamicsModel,
  parameters: Parameter[],
  pluginName: string,
  renders: CaptureRender[] = [],
): { header: string; params: CloneParam[] } {
  const params = dynamicsCloneParameters(model, parameters, renders);
  const cloneIndex = new Map(params.map((p, i) => [p.original, i]));
  const baseValue = new Map(model.baseValues.map((v) => [v.index, v.value]));
  const list = (values: number[]) => values.map(cppNumber).join(", ");

  const lines = [
    "// Generated by vst-cloner – do not edit.",
    "#pragma once",
    '#include "DynamicsEngine.h"',
    "",
    "namespace clonemodel",
    "{",
    `inline constexpr const char* pluginName = ${cppString(pluginName)};`,
    "",
    ...parameterLines(params),
    `inline constexpr vch::Detector detector = vch::Detector::${model.structure.detector};`,
    `inline constexpr vch::Topology topology = vch::Topology::${model.structure.topology};`,
    `inline constexpr double basePacked[vch::numPacked] = { ${list(pack(model.base))} };`,
    "",
  ];

  model.tables.forEach((t, i) => {
    lines.push(`inline const double tableValues${i}[] = { ${list(t.points.map((p) => p.value))} };`);
    lines.push(`inline const double tablePacked${i}[] = { ${list(t.points.flatMap((p) => p.packed))} };`);
  });
  if (model.tables.length === 0) {
    lines.push("inline const vch::ParamTable* const tables = nullptr;", "inline constexpr int numTables = 0;");
  } else {
    lines.push("inline const vch::ParamTable tables[] =", "{");
    model.tables.forEach((t, i) => {
      lines.push(`    { ${cloneIndex.get(t.index)}, ${t.discrete}, ${t.points.length}, tableValues${i}, tablePacked${i}, ${cppNumber(baseValue.get(t.index) ?? 0)} }, // ${t.name.replace(/[\r\n]/g, " ")}`);
    });
    lines.push("};", `inline constexpr int numTables = ${model.tables.length};`);
  }
  lines.push("} // namespace clonemodel", "");
  return { header: lines.join("\n"), params };
}
