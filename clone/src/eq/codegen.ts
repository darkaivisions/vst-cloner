import type { Parameter } from "@vst-cloner/profile";
import type { EqModel, ShapeFit } from "./model.ts";
import { cloneParameters, type CloneParam } from "./params.ts";
import type { ShapeKind } from "./mapping.ts";

/** C++ string literal (UTF-8 safe). */
export function cppString(text: string): string {
  return `"${[...new TextEncoder().encode(text)]
    .map((b) => (b === 0x22 ? '\\"' : b === 0x5c ? "\\\\" : b >= 0x20 && b < 0x7f ? String.fromCharCode(b) : `\\x${b.toString(16).padStart(2, "0")}""`))
    .join("")}"`;
}

export const cppNumber = (v: number) => {
  if (!Number.isFinite(v)) throw new Error(`non-finite value in model: ${v}`);
  const text = Number(v.toPrecision(15)).toString();
  return /[.e]/.test(text) ? text : `${text}.0`;
};

const KIND: Record<ShapeKind, string> = {
  bell: "bell", lowShelf: "lowShelf", highShelf: "highShelf", lowCut: "lowCut", highCut: "highCut",
  notch: "notch", bandPass: "bandPass", tiltShelf: "tiltShelf", flatTilt: "flatTilt", unsupported: "unsupported",
};

function shapeFit(kind: ShapeKind, fit: ShapeFit | undefined, index: number): string {
  const f: ShapeFit = fit ?? { design: "matched", freqScale: 1, qScale: 1 };
  const brickwall = f.brickwall ? `brickwall${index}, ${f.brickwall.sections.length}, ${cppNumber(f.brickwall.edgeScale)}` : "nullptr, 0, 1.0";
  return `{ vch::Kind::${KIND[kind]}, ${fit ? "true" : "false"}, vch::Design::${f.design}, ${cppNumber(f.freqScale)}, ${cppNumber(f.qScale)}, ` +
    `${cppNumber(f.qExponent ?? 1)}, ${cppNumber(f.gainScale ?? 1)}, vch::QMode::${f.qMode ?? "scaleAll"}, ${f.tiltOrder ?? 2}, ${brickwall} }`;
}

/** Parameter declarations shared by all plugin templates (see plugin-template/common/CloneParameters.h). */
export function parameterLines(params: CloneParam[]): string[] {
  const lines = [
    "struct ParamPoint { float norm, value; };",
    "enum class ParamKind { continuous, choice, toggle };",
    "struct ParamInfo",
    "{",
    "    const char* id; const char* name; ParamKind kind; float defaultValue;",
    "    const ParamPoint* points; int numPoints; bool log; const char* unit;",
    "    const char* const* choices; int numChoices;",
    "    int decimals; // −1: automatic",
    "};",
    "",
  ];
  params.forEach((p, i) => {
    if (p.points) lines.push(`inline const ParamPoint points${i}[] = { ${p.points.map(([n, v]) => `{ ${cppNumber(n)}f, ${cppNumber(v)}f }`).join(", ")} };`);
    if (p.choices) lines.push(`inline const char* const choices${i}[] = { ${p.choices.map(cppString).join(", ")} };`);
  });
  lines.push("", "inline const ParamInfo params[] =", "{");
  params.forEach((p, i) => {
    const kind = p.kind === "continuous" ? "continuous" : p.kind === "choice" ? "choice" : "toggle";
    lines.push(
      `    { ${cppString(p.id)}, ${cppString(p.name)}, ParamKind::${kind}, ${cppNumber(p.defaultValue)}f, ` +
        `${p.points ? `points${i}` : "nullptr"}, ${p.points?.length ?? 0}, ${p.log ? "true" : "false"}, ${cppString(p.unit ?? "")}, ` +
        `${p.choices ? `choices${i}` : "nullptr"}, ${p.choices?.length ?? 0}, ${p.decimals ?? -1} },`,
    );
  });
  lines.push("};", `inline constexpr int numParams = ${params.length};`, "");
  return lines;
}

/** Generates CloneModel.h for plugin-template/eq. */
export function generateModelHeader(model: EqModel, parameters: Parameter[], pluginName: string): { header: string; params: CloneParam[] } {
  const params = cloneParameters(model, parameters);
  const indexById = new Map(params.map((p, i) => [p.id, i]));
  const lines: string[] = [
    "// Generated by vst-cloner – do not edit.",
    "#pragma once",
    '#include "EqEngine.h"',
    "",
    "namespace clonemodel",
    "{",
    `inline constexpr const char* pluginName = ${cppString(pluginName)};`,
    "",
    "struct BandInfo { int enable, frequency, gain, q, shape, slope; };",
    "",
    ...parameterLines(params),
  ];

  const shapes = model.shapes.length > 0 ? model.shapes : [{ label: "bell", kind: (model.defaultKind ?? "bell") as ShapeKind, fit: model.defaultFit }];
  shapes.forEach((s, i) => {
    const sections = s.fit?.brickwall?.sections;
    if (sections) {
      lines.push(`inline const vch::PrototypeSection brickwall${i}[] = { ${sections.map((p) => `{ ${[...p.b, ...p.a].map(cppNumber).join(", ")} }`).join(", ")} };`);
    }
  });
  lines.push("inline const vch::ShapeFit shapes[] =", "{");
  shapes.forEach((s, i) => lines.push(`    ${shapeFit(s.kind, s.fit, i)}, // ${s.label.replace(/[\r\n]/g, " ")}`));
  lines.push("};", `inline constexpr int numShapes = ${shapes.length};`, "");

  // order 0 marks the "Brickwall" slope (elliptic prototype of the cut shapes)
  const orders = model.mapping.slopes?.map((s) => (s.brickwall ? 0 : s.order)) ?? [2];
  lines.push(`inline const int slopeOrders[] = { ${orders.join(", ")} };`, `inline constexpr int numSlopes = ${orders.length};`, "");

  const ref = (id: string) => indexById.get(id) ?? -1;
  lines.push("inline const BandInfo bands[] =", "{");
  for (const band of model.mapping.bands) {
    const p = `b${band.band}_`;
    lines.push(`    { ${ref(`${p}enable`)}, ${ref(`${p}freq`)}, ${ref(`${p}gain`)}, ${ref(`${p}q`)}, ${ref(`${p}shape`)}, ${ref(`${p}slope`)} },`);
  }
  lines.push(
    "};",
    `inline constexpr int numBands = ${model.mapping.bands.length};`,
    `inline constexpr int outputGainParam = ${ref("output_gain")};`,
    `inline constexpr double defaultQ = ${cppNumber(Math.SQRT1_2)};`,
    "} // namespace clonemodel",
    "",
  );

  return { header: lines.join("\n"), params };
}
